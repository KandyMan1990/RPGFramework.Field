using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace RPGFramework.Field.Editor
{
    [Serializable]
    public class FieldDatabase
    {
        private readonly string m_AssetBundlesPath = Path.Combine(Application.streamingAssetsPath, "Field");

        [SerializeField]
        private List<FieldDatabaseAssetAuthoring> m_Fields = new List<FieldDatabaseAssetAuthoring>();

        public List<FieldDatabaseAssetAuthoring> Fields => m_Fields;

        public void BuildScriptFile(string path, string filename, string namespaceForScript)
        {
            if (!Directory.Exists(path))
            {
                Directory.CreateDirectory(path);
            }

            string filePath = Path.Combine(path, filename);

            if (File.Exists(filePath))
            {
                File.Delete(filePath);
            }

            int           count          = m_Fields.Count;
            StringBuilder sb             = new StringBuilder();
            string        scriptFileName = filename.Split('.')[0];

            sb.AppendLine("// THIS FILE IS AUTOGENERATED, DO NOT MODIFY");
            sb.AppendLine($"// Last generated at {DateTime.UtcNow}\n");

            sb.AppendLine("using RPGFramework.Field;");
            sb.AppendLine("using System.IO;");
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine();
            sb.AppendLine($"namespace {namespaceForScript}");
            sb.AppendLine("{");

            sb.AppendLine($"\tinternal class {scriptFileName.Replace(" ", "")} : IFieldDatabase");
            sb.AppendLine("\t{");
            sb.AppendLine("\t\tprivate readonly FieldDatabaseAsset[] m_Fields;");
            sb.AppendLine();
            sb.AppendLine($"\t\tinternal {scriptFileName.Replace(" ", "")}()");
            sb.AppendLine("\t\t{");

            sb.AppendLine("\t\t\tstring assetBundlesPath = Path.Combine(Application.streamingAssetsPath, \"Field\");");
            sb.AppendLine("\t\t\tm_Fields = new FieldDatabaseAsset[]");
            sb.AppendLine("\t\t\t{");
            for (int i = 0; i < count; i++)
            {
                sb.AppendLine($"\t\t\t\tnew FieldDatabaseAsset(\"{m_Fields[i].Prefab.name}\", Path.Combine(assetBundlesPath, \"{m_Fields[i].Prefab.name.ToLower()}\"),");
                sb.AppendLine("\t\t\t\t\tnew string[]");
                sb.AppendLine("\t\t\t\t\t{");
                for (int j = 0; j < m_Fields[i].LocalisationSheets.Length; j++)
                {
                    sb.AppendLine($"\t\t\t\t\t\t\"{m_Fields[i].LocalisationSheets[j].SheetName}\",");
                }

                sb.AppendLine("\t\t\t\t\t}");
                sb.AppendLine($"\t\t\t\t),");
            }

            sb.AppendLine("\t\t\t};");

            sb.AppendLine("\t\t}");

            sb.AppendLine();

            sb.AppendLine("\t\tFieldDatabaseAsset IFieldDatabase.Get(int index)");
            sb.AppendLine("\t\t{");
            sb.AppendLine("\t\t\treturn m_Fields[index];");
            sb.AppendLine("\t\t}");

            sb.AppendLine("\t}");

            sb.AppendLine("}");

            string file = sb.ToString();

            File.WriteAllText(filePath, file);

            AssetDatabase.Refresh();
        }

        public void BuildAssetBundles()
        {
            int count = m_Fields.Count;
            if (count == 0)
            {
                return;
            }

            if (Directory.Exists(m_AssetBundlesPath))
            {
                Directory.Delete(m_AssetBundlesPath, true);
            }

            Directory.CreateDirectory(m_AssetBundlesPath);

            AssetBundleBuild[] fieldsToBuild = new AssetBundleBuild[count];

            for (int i = 0; i < count; i++)
            {
                string prefabPath = AssetDatabase.GetAssetPath(m_Fields[i].Prefab);

                fieldsToBuild[i] = new AssetBundleBuild
                                   {
                                       assetBundleName = m_Fields[i].Prefab.name,
                                       assetNames      = new string[] { prefabPath }
                                   };
            }

            const BuildAssetBundleOptions options = BuildAssetBundleOptions.ChunkBasedCompression | BuildAssetBundleOptions.StrictMode;

            BuildPipeline.BuildAssetBundles(m_AssetBundlesPath, fieldsToBuild, options, EditorUserBuildSettings.activeBuildTarget);

            AssetDatabase.Refresh();
        }
    }
}