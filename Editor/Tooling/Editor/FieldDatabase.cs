        public void BuildScriptFile(string path, string filename, string namespaceForScript)
        {
            if (!Directory.Exists(path))
            {
                Directory.CreateDirectory(path);
            }

            string filePath = Path.Combine(path, filename);

            if (File.Exists(filePath))
            {
                File.Delete(filePath);
            }

            int           count          = m_Fields.Count;
            StringBuilder sb             = new StringBuilder();
            string        scriptFileName = filename.Split('.')[0];

            sb.AppendLine("// THIS FILE IS AUTOGENERATED, DO NOT MODIFY");
            sb.AppendLine($"// Last generated at {DateTime.UtcNow}\n");

            sb.AppendLine("using RPGFramework.Field;");
            sb.AppendLine("using RPGFramework.Hashing;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using System.IO;");
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine();
            sb.AppendLine($"namespace {namespaceForScript}");
            sb.AppendLine("{");

            sb.AppendLine($"\tinternal class {scriptFileName.Replace(" ", "")} : IFieldDatabase");
            sb.AppendLine("\t{");
            sb.AppendLine("\t\tprivate readonly Dictionary<ulong, FieldDatabaseAsset> m_FieldsByNameHash;");
            sb.AppendLine();
            sb.AppendLine($"\t\tinternal {scriptFileName.Replace(" ", "")}()");
            sb.AppendLine("\t\t{");

            sb.AppendLine("\t\t\tstring assetBundlesPath = Path.Combine(Application.streamingAssetsPath, \"Field\");");
            sb.AppendLine($"\t\t\tm_FieldsByNameHash = new Dictionary<ulong, FieldDatabaseAsset>({count})");
            sb.AppendLine("\t\t\t{");
            for (int i = 0; i < count; i++)
            {
                string fieldName = m_Fields[i].Prefab.name;

                sb.AppendLine($"\t\t\t\t[Fnv1a64.Hash(\"{fieldName}\")] = new FieldDatabaseAsset(\"{fieldName}\", Path.Combine(assetBundlesPath, \"{fieldName.ToLower()}\"),");
                sb.AppendLine("\t\t\t\t\tnew string[]");
                sb.AppendLine("\t\t\t\t\t{");
                for (int j = 0; j < m_Fields[i].LocalisationSheets.Length; j++)
                {
                    sb.AppendLine($"\t\t\t\t\t\t\"{m_Fields[i].LocalisationSheets[j].SheetName}\",");
                }

                sb.AppendLine("\t\t\t\t\t}");
                sb.AppendLine($"\t\t\t\t),");
            }

            sb.AppendLine("\t\t\t};");

            sb.AppendLine("\t\t}");

            sb.AppendLine();

            sb.AppendLine("\t\tFieldDatabaseAsset IFieldDatabase.Get(ulong fieldNameHash)");
            sb.AppendLine("\t\t{");
            sb.AppendLine("\t\t\treturn m_FieldsByNameHash[fieldNameHash];");
            sb.AppendLine("\t\t}");

            sb.AppendLine("\t}");

            sb.AppendLine("}");

            string file = sb.ToString();

            File.WriteAllText(filePath, file);

            AssetDatabase.Refresh();
        }

        /// <summary>
        /// Check every field's entities before their data is exported.<br /><br />
        /// Script 0 is an entity's init script by convention, and the field module runs it at load. An
        /// entity whose scripts were authored in another order would have its enter or interaction
        /// script executed at field load, firing gameplay logic nobody triggered.<br /><br />
        /// This is checked here rather than at runtime deliberately. A per-load check re-proves the same
        /// thing on every field load forever, and reports the problem while playing; checking as the
        /// runtime data is built reports it once, while authoring, to the person who can fix it.
        /// </summary>
        /// <returns>A readable problem per offending entity. Empty means every field is well-formed.</returns>
        public List<string> ValidateFields()
        {
            List<string> problems = new List<string>();

            for (int i = 0; i < m_Fields.Count; i++)
            {
                GameObject prefab = m_Fields[i].Prefab;

                if (prefab == null)
                {
                    problems.Add($"Field [{i}] has no prefab assigned");
                    continue;
                }

                FieldEntities fieldEntities = prefab.GetComponent<FieldEntities>();

                if (fieldEntities == null)
                {
                    problems.Add($"{prefab.name} has no {nameof(FieldEntities)} on its root, so it has no entities. Run RPG Framework / Field / Migrate Entities To Records");
                    continue;
                }

                Dictionary<int, int> scriptCounts     = new Dictionary<int, int>();
                HashSet<int>         withBodies       = new HashSet<int>();
                HashSet<int>         entityIds        = new HashSet<int>();
                HashSet<FieldEntity> bodies           = new HashSet<FieldEntity>();
                DialogueChannelUse   dialogueChannels = new DialogueChannelUse();

                foreach (FieldEntityRecord record in fieldEntities.Entities)
                {
                    scriptCounts[record.EntityId] = record.Scripts.Count;

                    if (record.Body != null)
                    {
                        withBodies.Add(record.EntityId);
                    }
                }

                foreach (FieldEntityRecord record in fieldEntities.Entities)
                {
                    ValidateEntity(prefab, fieldEntities.Dimension, record, entityIds, bodies, scriptCounts, withBodies, dialogueChannels, problems);
                }

                // A body no record claims is never bound, so its triggers never fire and nothing can move or show it.
                foreach (FieldEntity body in prefab.GetComponentsInChildren<FieldEntity>(true))
                {
                    if (!bodies.Contains(body))
                    {
                        problems.Add($"{prefab.name} / '{body.name}' has a {nameof(FieldEntity)} no entity uses as its body, so nothing drives it. Give an entity it as its body in the Field Designer, or remove the component");
                    }
                }

                dialogueChannels.Validate(prefab.name, problems);
            }

            ValidateVariableMaps(problems);

            return problems;
        }

        /// <summary>
        /// The variable map is part of what a field export depends on: a new game begins at the defaults of
        /// <see cref="FieldVariables.CURRENT_FIELD" /> and <see cref="FieldVariables.CURRENT_SPAWN" />, so they have to
        /// name a field in this database and a spawn point it has, and the map has to declare everything the
        /// framework reads from it.
        /// </summary>
        private void ValidateVariableMaps(List<string> problems)
        {
            string[] guids = AssetDatabase.FindAssets("t:" + nameof(VariableMapAsset));

            if (guids.Length == 0)
            {
                problems.Add($"No {nameof(VariableMapAsset)} in the project. A new game reads where to begin from it — create one with RPG Framework / Core / Variable Map");
                return;
            }

            foreach (string guid in guids)
            {
                VariableMapAsset map = AssetDatabase.LoadAssetAtPath<VariableMapAsset>(AssetDatabase.GUIDToAssetPath(guid));

                foreach (string problem in map.Validate())
                {
                    problems.Add($"Variable map '{map.name}': {problem}");
                }

                if (!map.TryGetVariable(FieldVariables.CURRENT_FIELD, out VariableDefinition field) ||
                    !map.TryGetVariable(FieldVariables.CURRENT_SPAWN, out VariableDefinition spawn))
                {
                    continue;
                }

                GameObject start = FindFieldPrefab(field.DefaultValue);

                if (start == null)
                {
                    problems.Add($"Variable map '{map.name}': '{FieldVariables.CURRENT_FIELD}' does not default to a field in this database, so a new game has nowhere to begin. Choose one in the Variable Map inspector");
                    continue;
                }

                int spawnId = (int)VariableDefaults.ToInteger(spawn.DefaultValue, VariableWidth.Int);

                if (Array.Find(start.GetComponentsInChildren<SpawnPoint>(true), spawnPoint => spawnPoint.Id == spawnId) == null)
                {
                    problems.Add($"Variable map '{map.name}': '{FieldVariables.CURRENT_SPAWN}' defaults to spawn point [{spawnId}], which {start.name} does not have");
                }
            }
        }

        private GameObject FindFieldPrefab(ulong fieldNameHash)
        {
            foreach (FieldDatabaseAssetAuthoring field in m_Fields)
            {
                if (field.Prefab != null && Fnv1a64.Hash(field.Prefab.name) == fieldNameHash)
                {
                    return field.Prefab;
                }
            }

            return null;
        }

        /// <summary>
        /// A field entity's rigidbody has to be kinematic.<br /><br />
        /// Entities are never moved by the physics simulation: the movement drivers sweep a kinematic body
        /// along its path and slide it along what it meets. A dynamic body instead takes momentum from every
        /// collision — walk into one and both float away, with nothing to slow them — so it is refused here,
        /// where it can be fixed, rather than discovered in play.
        /// </summary>
        private static void ValidateEntityPhysics(FieldDimension dimension, FieldEntity entity, string entityName, List<string> problems)
        {
            // The movement drivers look for a 3D body before a 2D one, so the wrong kind is not a slower entity but
            // a still one.
            if (dimension == FieldDimension.TwoD && entity.TryGetComponent(out Rigidbody _))
            {
                problems.Add($"{entityName} has a 3D {nameof(Rigidbody)} in a 2D field. Use a {nameof(Rigidbody2D)}, or set the field to 3D on its {nameof(FieldEntities)}");
            }

            if (dimension == FieldDimension.ThreeD && entity.TryGetComponent(out Rigidbody2D _))
            {
                problems.Add($"{entityName} has a {nameof(Rigidbody2D)} in a 3D field. Use a {nameof(Rigidbody)}, or set the field to 2D on its {nameof(FieldEntities)}");
            }

            if (entity.TryGetComponent(out Rigidbody body) && !body.isKinematic)
            {
                problems.Add($"{entityName} has a dynamic {nameof(Rigidbody)}. Field entities must be kinematic, so collisions cannot push them — tick Is Kinematic");
            }

            if (entity.TryGetComponent(out Rigidbody2D body2D) && body2D.bodyType != RigidbodyType2D.Kinematic)
            {
                problems.Add($"{entityName} has a {body2D.bodyType} {nameof(Rigidbody2D)}. Field entities must be kinematic, so collisions cannot push them — set Body Type to Kinematic");
            }
        }

        /// <summary>
        /// Everything about one entity that has to be true before its field is exported, and that cannot
        /// change afterwards. The VM addresses entities and scripts by index at runtime with no way to
        /// report which authored thing was wrong, so it is all decided here instead.
        /// </summary>
        private void ValidateEntity(GameObject prefab, FieldDimension dimension, FieldEntityRecord record, HashSet<int> entityIds, HashSet<FieldEntity> bodies, Dictionary<int, int> scriptCounts, HashSet<int> withBodies, DialogueChannelUse dialogueChannels, List<string> problems)
        {
            string      entityName = $"{prefab.name} / '{record.Name}'";
            FieldEntity body       = record.Body;

            // Scripts address each other by entity id, so two entities sharing one makes the target
            // ambiguous — and the VM's entity dictionary would throw on the duplicate key at load.
            if (!entityIds.Add(record.EntityId))
            {
                problems.Add($"{entityName} reuses entity id [{record.EntityId}], which another entity in this field already has");
            }

            if (body != null)
            {
                if (!bodies.Add(body))
                {
                    problems.Add($"{entityName} uses '{body.name}' as its body, which another entity already does");
                }

                ValidateEntityPhysics(dimension, body, entityName, problems);
                ValidateCollisionTrigger(dimension, body, entityName, problems);
            }

            if (record.Scripts.Count == 0)
            {
                problems.Add($"{entityName} declares no scripts, so it has no init script");
                return;
            }

            FieldScriptType firstScriptType = record.Scripts[0].Type;

            if (firstScriptType != FieldScriptType.Init)
            {
                problems.Add($"{entityName} has [{firstScriptType}] as its first script, but script 0 is run at field load as the init script. Reorder so the {nameof(FieldScriptType.Init)} script is first");
            }

            int initScriptCount    = 0;
            int defaultScriptCount = 0;

            for (int i = 0; i < record.Scripts.Count; i++)
            {
                FieldScriptRecord script = record.Scripts[i];

                if (script.Type == FieldScriptType.Init)
                {
                    initScriptCount++;
                }

                if (script.Type == FieldScriptType.Default)
                {
                    defaultScriptCount++;
                }

                string scriptDescription = $"{entityName} script [{i}] ({script.Type})";
                string text              = script.Text ?? string.Empty;

                try
                {
                    FieldScriptCompiler.Compile(text);
                }
                catch (Exception e)
                {
                    problems.Add($"{scriptDescription} does not compile: {e.Message}");
                    continue;
                }

                string[] lines = text.Split('\n');

                ValidateInitScript(script.Type, scriptDescription, lines, problems);
                ValidateBodyOpcodes(body, scriptDescription, lines, problems);
                ValidateEntityTargets(scriptCounts, withBodies, scriptDescription, lines, problems);
                ValidateAnimationOpcodes(body, scriptDescription, lines, problems);
                ValidateScriptRequests(record, scriptCounts, scriptDescription, lines, problems);
                ValidateTriggerSwitches(body, scriptDescription, lines, problems);
                ValidateMapJumps(scriptDescription, lines, problems);
                ValidateGatewayScript(script.Type, scriptDescription, lines, problems);
                dialogueChannels.Read(lines, scriptDescription);
            }

            if (initScriptCount > 1)
            {
                problems.Add($"{entityName} has {initScriptCount} {nameof(FieldScriptType.Init)} scripts, but only script 0 is run at load");
            }

            if (defaultScriptCount > 1)
            {
                problems.Add($"{entityName} has {defaultScriptCount} {nameof(FieldScriptType.Default)} scripts, but only one is started after initialisation");
            }

            ValidateGateway(prefab, record, entityName, problems);
            ValidatePushScript(record, entityName, problems);
        }

        /// <summary>
        /// A collision trigger is only a trigger if something can enter it, and only in the dimension the field is
        /// built in: a 3D collider reports nothing to a 2D body, and the other way round.
        /// </summary>
        private static void ValidateCollisionTrigger(FieldDimension dimension, FieldEntity body, string entityName, List<string> problems)
        {
            FieldCollisionTrigger trigger = body.GetComponentInChildren<FieldCollisionTrigger>(true);

            if (trigger == null)
            {
                return;
            }

            bool has3D = trigger.TryGetComponent(out Collider collider3D);
            bool has2D = trigger.TryGetComponent(out Collider2D collider2D);

            if (!has3D && !has2D)
            {
                problems.Add($"{entityName}'s {nameof(FieldCollisionTrigger)} has no collider, so nothing can enter or leave it");
                return;
            }

            if (has3D && !collider3D.isTrigger)
            {
                problems.Add($"{entityName}'s {nameof(FieldCollisionTrigger)} has a solid collider, so it blocks the player instead of letting them through — tick Is Trigger");
            }

            if (has2D && !collider2D.isTrigger)
            {
                problems.Add($"{entityName}'s {nameof(FieldCollisionTrigger)} has a solid 2D collider, so it blocks the player instead of letting them through — tick Is Trigger");
            }

            if (dimension == FieldDimension.ThreeD && !has3D)
            {
                problems.Add($"{entityName}'s {nameof(FieldCollisionTrigger)} has only a 2D collider in a 3D field, so the player never enters it");
            }

            if (dimension == FieldDimension.TwoD && !has2D)
            {
                problems.Add($"{entityName}'s {nameof(FieldCollisionTrigger)} has only a 3D collider in a 2D field, so the player never enters it");
            }
        }

        private static bool HasScript(FieldEntityRecord record, FieldScriptType scriptType)
        {
            bool hasScript = record.Scripts.Exists(script => script.Type == scriptType);

            return hasScript;
        }

        /// <summary>
        /// A script request names an entity by id and one of its scripts by event id — a position in that entity's
        /// list. Deleting either leaves the number pointing at nothing, or at whatever moved into its place, and the
        /// VM looks entities up by id with nothing to say when one is missing.
        /// </summary>
        private static void ValidateScriptRequests(FieldEntityRecord record, Dictionary<int, int> scriptCounts, string scriptDescription, string[] lines, List<string> problems)
        {
            foreach (string line in lines)
            {
                string[] parts = line.Trim().Split(' ');

                if (!FieldOpCodeCatalogue.TryGet(parts[0], out FieldOpCodeInfo opCode))
                {
                    continue;
                }

                int entityArgument = ArgumentIndex(opCode, ArgumentType.EntityId);
                int eventArgument  = ArgumentIndex(opCode, ArgumentType.EventId);

                if (eventArgument < 0 || eventArgument + 1 >= parts.Length || entityArgument + 1 >= parts.Length)
                {
                    continue;
                }

                // With no entity named, the event is one of this entity's own, as RETURN_TO_SCRIPT's is.
                string entityToken = entityArgument < 0 ? record.EntityId.ToString(CultureInfo.InvariantCulture) : parts[entityArgument + 1];

                ValidateScriptRequest(entityToken, parts[eventArgument + 1], scriptCounts, parts[0], scriptDescription, problems);
            }
        }

        private static int ArgumentIndex(FieldOpCodeInfo opCode, ArgumentType type)
        {
            int argumentIndex = -1;

            for (int argument = 0; argument < opCode.Arguments.Count; argument++)
            {
                if (opCode.Arguments[argument].Type == type)
                {
                    argumentIndex = argument;
                    break;
                }
            }

            return argumentIndex;
        }

        private static void ValidateScriptRequest(string entityToken, string eventToken, Dictionary<int, int> scriptCounts, string opCodeName, string scriptDescription, List<string> problems)
        {
            // A request worked out while playing is only known then.
            if (entityToken.StartsWith("$") || eventToken.StartsWith("$"))
            {
                return;
            }

            if (!int.TryParse(entityToken, NumberStyles.Integer, CultureInfo.InvariantCulture, out int entityId) ||
                !int.TryParse(eventToken,  NumberStyles.Integer, CultureInfo.InvariantCulture, out int eventId))
            {
                return;
            }

            if (!scriptCounts.TryGetValue(entityId, out int count))
            {
                problems.Add($"{scriptDescription} uses {opCodeName} on entity [{entityId}], which this field has no entity for");
                return;
            }

            if (eventId < 0 || eventId >= count)
            {
                problems.Add($"{scriptDescription} uses {opCodeName} to run event [{eventId}] on entity [{entityId}], which has {count} script(s), so there is no such event");
            }
        }

        /// <summary>
        /// An opcode acting on the entity's presence that names another entity — to face it, to walk up to it — acts
        /// toward that entity's body, so the one it names needs a body too.
        /// </summary>
        private static void ValidateEntityTargets(Dictionary<int, int> scriptCounts, HashSet<int> withBodies, string scriptDescription, string[] lines, List<string> problems)
        {
            foreach (string line in lines)
            {
                string[] parts = line.Trim().Split(' ');

                if (!FieldOpCodeCatalogue.TryGet(parts[0], out FieldOpCodeInfo opCode) || !opCode.NeedsBody)
                {
                    continue;
                }

                for (int argument = 0; argument < opCode.Arguments.Count && argument + 1 < parts.Length; argument++)
                {
                    string token = parts[argument + 1];

                    // One worked out while playing is only known then.
                    if (opCode.Arguments[argument].Type != ArgumentType.EntityId || token.StartsWith("$") ||
                        !int.TryParse(token, NumberStyles.Integer, CultureInfo.InvariantCulture, out int targetEntityId))
                    {
                        continue;
                    }

                    if (!scriptCounts.ContainsKey(targetEntityId))
                    {
                        problems.Add($"{scriptDescription} uses {parts[0]} toward entity [{targetEntityId}], which this field has no entity for");
                    }
                    else if (!withBodies.Contains(targetEntityId))
                    {
                        problems.Add($"{scriptDescription} uses {parts[0]} toward entity [{targetEntityId}], which has no body to face or walk up to. Give it one in the Field Designer");
                    }
                }
            }
        }

        /// <summary>
        /// An entity with no body has nowhere to be, nothing to show and nothing to walk into, so an opcode that acts
        /// on any of that has no answer. Give the entity a body, or move the opcode to an entity that has one.
        /// </summary>
        private static void ValidateBodyOpcodes(FieldEntity body, string scriptDescription, string[] lines, List<string> problems)
        {
            if (body != null)
            {
                return;
            }

            foreach (string line in lines)
            {
                string name = line.Trim().Split(' ')[0];

                if (FieldOpCodeCatalogue.TryGet(name, out FieldOpCodeInfo opCode) && opCode.NeedsBody)
                {
                    problems.Add($"{scriptDescription} uses {name}, which acts on the entity's presence in the field, but the entity has no body. Give it one in the Field Designer, or move the opcode to an entity that has one");
                }
            }
        }

        /// <summary>
        /// An animation opcode needs something to animate. The Animator lives on the visuals a game supplies rather
        /// than on the body the framework builds, so a body with no visuals, or visuals with no Animator, has
        /// nothing for these to drive.
        /// </summary>
        private static void ValidateAnimationOpcodes(FieldEntity body, string scriptDescription, string[] lines, List<string> problems)
        {
            if (body == null)
            {
                return;
            }

            Animator animator = body.GetComponentInChildren<Animator>(true);

            foreach (string line in lines)
            {
                string[] parts = line.Trim().Split(' ');

                if (!FieldOpCodeCatalogue.TryGet(parts[0], out FieldOpCodeInfo opCode) || !opCode.NeedsAnimator)
                {
                    continue;
                }

                if (animator == null)
                {
                    problems.Add($"{scriptDescription} uses {parts[0]}, but the entity's body has no Animator. Give its visuals one, or move the opcode to an entity whose visuals animate");
                    continue;
                }

                if (animator.runtimeAnimatorController == null)
                {
                    problems.Add($"{scriptDescription} uses {parts[0]}, but the Animator on [{animator.gameObject.name}] has no controller, so it plays nothing and the entity holds its bind pose");
                    continue;
                }

                ValidateAnimationNames(animator, opCode, parts, scriptDescription, problems);
            }
        }

        /// <summary>
        /// A state the controller does not have. The name is hashed into the bytecode, so nothing downstream can tell
        /// it was a typo — the entity simply stays as it was.
        /// </summary>
        private static void ValidateAnimationNames(Animator animator, FieldOpCodeInfo opCode, string[] parts, string scriptDescription, List<string> problems)
        {
            for (int argument = 0; argument < opCode.Arguments.Count; argument++)
            {
                if (opCode.Arguments[argument].Type != ArgumentType.AnimationName || argument + 1 >= parts.Length)
                {
                    continue;
                }

                string                      stateName = parts[argument + 1];
                Dictionary<string, AnimatorState> states  = States(animator);

                if (!states.TryGetValue(stateName, out AnimatorState state))
                {
                    problems.Add(NoSuchStateProblem(animator, states, stateName, scriptDescription));
                    continue;
                }

                ValidatePlaybackSpeed(animator, state, stateName, scriptDescription, problems);
                ValidateStateStays(animator, state, stateName, scriptDescription, problems);
            }
        }

        /// <summary>
        /// Arguments are read one word at a time, so a state whose name contains a space is cut at the first and can
        /// never be named. Saying which state was meant turns a confusing miss into a rename.
        /// </summary>
        private static string NoSuchStateProblem(Animator animator, Dictionary<string, AnimatorState> states, string stateName, string scriptDescription)
        {
            foreach (string candidate in states.Keys)
            {
                if (!candidate.StartsWith(stateName + " ", StringComparison.Ordinal))
                {
                    continue;
                }

                return $"{scriptDescription} names the animation [{stateName}], which is [{candidate}] on [{animator.gameObject.name}] cut at its first space. An animation name is read one word at a time, so rename the state without spaces";
            }

            string noSuchState = $"{scriptDescription} names the animation [{stateName}], which the controller on [{animator.gameObject.name}] has no state for. It has {string.Join(", ", states.Keys)}";

            return noSuchState;
        }

        /// <summary>
        /// A state that will not advance. A state's playback speed can be multiplied by a float parameter, which is
        /// how a controller matches a walk cycle to input; the framework writes only the parameters in
        /// <c>AnimatorAnimationDriver</c>, so any other one sits at its default. A default of zero holds the
        /// animation on its first frame while the pose still changes, which reads as a rig that will not animate.
        /// </summary>
        private static void ValidatePlaybackSpeed(Animator animator, AnimatorState state, string stateName, string scriptDescription, List<string> problems)
        {
            if (state.speed == 0f)
            {
                problems.Add($"{scriptDescription} names the animation [{stateName}], whose speed is 0 in the controller on [{animator.gameObject.name}], so it will hold its first frame");

                return;
            }

            if (!state.speedParameterActive)
            {
                return;
            }

            foreach (AnimatorControllerParameter parameter in Controller(animator).parameters)
            {
                if (parameter.name != state.speedParameter || parameter.defaultFloat != 0f)
                {
                    continue;
                }

                problems.Add($"{scriptDescription} names the animation [{stateName}], whose speed in the controller on [{animator.gameObject.name}] is multiplied by the parameter [{parameter.name}]. Nothing sets it and it defaults to 0, so the animation will hold its first frame. Give it a default of 1, or clear the state's speed multiplier");
            }
        }

        /// <summary>
        /// A state the controller leaves by itself — an exit time with no condition — ends before a script expects: a
        /// played animation stops short and cannot be held or looped, and a base animation drifts off into another
        /// state. It is a controller built for something that drives it differently, as a character controller does.
        /// </summary>
        private static void ValidateStateStays(Animator animator, AnimatorState state, string stateName, string scriptDescription, List<string> problems)
        {
            foreach (AnimatorStateTransition transition in state.transitions)
            {
                if (!transition.hasExitTime || transition.conditions.Length > 0)
                {
                    continue;
                }

                string destination = transition.destinationState != null        ? transition.destinationState.name :
                                     transition.destinationStateMachine != null ? transition.destinationStateMachine.name : "the exit";

                problems.Add($"{scriptDescription} names the animation [{stateName}], which the controller on [{animator.gameObject.name}] leaves by itself {transition.exitTime:0.##} of the way through, for [{destination}]. It would stop short of its end, and could not be held or looped. Turn off that transition's exit time, or give it a condition");
            }
        }

        /// <summary>
        /// Every state in the controller by name, sub-state machines included. Reached through the editor's controller
        /// type because a running Animator cannot be asked what states it has.
        /// </summary>
        private static Dictionary<string, AnimatorState> States(Animator animator)
        {
            Dictionary<string, AnimatorState> states = new Dictionary<string, AnimatorState>();

            AnimatorController controller = Controller(animator);

            if (controller == null)
            {
                return states;
            }

            foreach (AnimatorControllerLayer layer in controller.layers)
            {
                CollectStates(layer.stateMachine, states);
            }

            return states;
        }

        private static AnimatorController Controller(Animator animator)
        {
            RuntimeAnimatorController runtime = animator.runtimeAnimatorController;

            if (runtime is AnimatorOverrideController overrideController)
            {
                runtime = overrideController.runtimeAnimatorController;
            }

            AnimatorController controller = runtime as AnimatorController;

            return controller;
        }

        private static void CollectStates(AnimatorStateMachine stateMachine, Dictionary<string, AnimatorState> states)
        {
            foreach (ChildAnimatorState state in stateMachine.states)
            {
                states[state.state.name] = state.state;
            }

            foreach (ChildAnimatorStateMachine child in stateMachine.stateMachines)
            {
                CollectStates(child.stateMachine, states);
            }
        }

        /// <summary>
        /// An init script that stops.<br /><br />
        /// Init runs straight through before the field is shown, so an opcode that blocks or ends the frame
        /// stops it there and everything after it never runs. The opcodes that do that declare
        /// <see cref="FieldOpCodeAttribute.StopsInit" />, so this reads the table rather than a list kept here.
        /// </summary>
        private static void ValidateInitScript(FieldScriptType scriptType, string scriptDescription, string[] lines, List<string> problems)
        {
            if (scriptType != FieldScriptType.Init)
            {
                return;
            }

            foreach (string line in lines)
            {
                string name = line.Trim().Split(' ')[0];

                if (FieldOpCodeCatalogue.TryGet(name, out FieldOpCodeInfo opCode) && opCode.StopsInit)
                {
                    problems.Add($"{scriptDescription} uses {name}, which waits or gives up the frame. Init runs straight through before the field is shown, so nothing after it would run — move it, and whatever follows it, into a {nameof(FieldScriptType.Default)} script");
                }
            }
        }

        /// <summary>
        /// A script switching a trigger its entity does not have. The field module reaches for the trigger
        /// without looking, so this is the only place the mistake can be caught.
        /// </summary>
        private static void ValidateTriggerSwitches(FieldEntity body, string scriptDescription, string[] lines, List<string> problems)
        {
            bool hasCollisionTrigger   = body != null && body.GetComponentInChildren<FieldCollisionTrigger>(true)   != null;
            bool hasInteractionTrigger = body != null && body.GetComponentInChildren<FieldInteractionTrigger>(true) != null;

            foreach (string line in lines)
            {
                string name = line.Trim().Split(' ')[0];

                if (!FieldOpCodeCatalogue.TryGet(name, out FieldOpCodeInfo opCode))
                {
                    continue;
                }

                if (opCode.OpCode == FieldScriptOpCode.CollisionTriggerActivation && !hasCollisionTrigger)
                {
                    problems.Add($"{scriptDescription} uses {name}, but its entity has no {nameof(FieldCollisionTrigger)} to switch");
                }

                if ((opCode.OpCode == FieldScriptOpCode.InteractionTriggerActivation || opCode.OpCode == FieldScriptOpCode.SetInteractionRange) && !hasInteractionTrigger)
                {
                    problems.Add($"{scriptDescription} uses {name}, but its entity has no {nameof(FieldInteractionTrigger)} to change");
                }
            }
        }

        /// <summary>
        /// A way out of the field that is not a <see cref="FieldScriptType.Gateway" /> script, or a gateway that is
        /// not a way out.<br /><br />
        /// <c>GATEWAY_TRIGGER_ACTIVATION</c> switches scripts by their type, so the type is a promise about what the
        /// script does, and it is kept here. A gateway that never jumps is silenced by that switch for no reason; a
        /// jump on entering that is typed as something else is a way out the switch cannot stop, which is the whole
        /// point of the switch. Other script types are left alone: a cutscene ending in a map jump is ordinary, and
        /// only entering the trigger is what the switch is about.
        /// </summary>
        private static void ValidateGatewayScript(FieldScriptType scriptType, string scriptDescription, string[] lines, List<string> problems)
        {
            bool isGateway = scriptType == FieldScriptType.Gateway;
            bool isOnEnter = scriptType == FieldScriptType.OnEnter;

            if (!isGateway && !isOnEnter)
            {
                return;
            }

            bool jumps = HasMapJump(lines);

            if (isGateway == jumps)
            {
                return;
            }

            FieldOpCodeCatalogue.TryGet(FieldScriptOpCode.JumpToAnotherMap, out FieldOpCodeInfo jump);

            if (isGateway)
            {
                problems.Add($"{scriptDescription} is a {nameof(FieldScriptType.Gateway)} script with no {jump.ScriptName} in it, so it is not a way out of the field. {nameof(FieldScriptType.Gateway)} is what GATEWAY_TRIGGER_ACTIVATION switches — if this script does something else on entering, make it an {nameof(FieldScriptType.OnEnter)} script");
                return;
            }

            problems.Add($"{scriptDescription} is an {nameof(FieldScriptType.OnEnter)} script containing {jump.ScriptName}, so it is a way out of the field that GATEWAY_TRIGGER_ACTIVATION cannot stop. Make it a {nameof(FieldScriptType.Gateway)} script");
        }

        private static bool HasMapJump(string[] lines)
        {
            foreach (string line in lines)
            {
                if (FieldOpCodeCatalogue.TryGet(line.Trim().Split(' ')[0], out FieldOpCodeInfo opCode) && opCode.OpCode == FieldScriptOpCode.JumpToAnotherMap)
                {
                    return true;
                }
            }

            return false;
        }

        /// <summary>
        /// A map jump to a spawn point the field it names does not have. The name itself is checked when the
        /// script compiles; the spawn id is not, and at run time the player arrives wherever their init script
        /// left them instead. A spawn id read from a variable is only known then, so it is left alone.
        /// </summary>
        private void ValidateMapJumps(string scriptDescription, string[] lines, List<string> problems)
        {
            foreach (string line in lines)
            {
                string[] parts = line.Trim().Split(' ');

                if (!FieldOpCodeCatalogue.TryGet(parts[0], out FieldOpCodeInfo opCode) || opCode.OpCode != FieldScriptOpCode.JumpToAnotherMap)
                {
                    continue;
                }

                // A jump written with the wrong arguments, or naming a field nothing answers to, is the
                // compiler's to report, and it will not have produced the bytecode this entity holds.
                if (parts.Length < 3 || parts[2].StartsWith("$") || !int.TryParse(parts[2], NumberStyles.Integer, CultureInfo.InvariantCulture, out int spawnId))
                {
                    continue;
                }

                GameObject destination = FindFieldPrefab(parts[1]);

                if (destination == null)
                {
                    continue;
                }

                if (Array.Find(destination.GetComponentsInChildren<SpawnPoint>(true), spawnPoint => spawnPoint.Id == spawnId) == null)
                {
                    problems.Add($"{scriptDescription} jumps to spawn point [{spawnId}] in {parts[1]}, which has no {nameof(SpawnPoint)} with that id");
                }
            }
        }

        private GameObject FindFieldPrefab(string fieldName)
        {
            foreach (FieldDatabaseAssetAuthoring field in m_Fields)
            {
                if (field.Prefab != null && field.Prefab.name == fieldName)
                {
                    return field.Prefab;
                }
            }

            return null;
        }

        /// <summary>
        /// A push script runs when the player walks into the entity's body, so on an entity with no body, or with nothing
        /// but triggers on it, nothing can walk into it and nothing runs it.
        /// </summary>
        private static void ValidatePushScript(FieldEntityRecord record, string entityName, List<string> problems)
        {
            if (!HasScript(record, FieldScriptType.OnPush) || HasSolidCollider(record.Body))
            {
                return;
            }

            string missing = record.Body == null ? "no body" : "nothing but triggers on its body";

            problems.Add($"{entityName} has an {nameof(FieldScriptType.OnPush)} script but {missing}, so nothing can walk into it and nothing runs it");
        }

        private static bool HasSolidCollider(FieldEntity body)
        {
            bool hasSolidCollider = false;

            if (body != null)
            {
                foreach (Collider collider in body.GetComponentsInChildren<Collider>(true))
                {
                    hasSolidCollider |= !collider.isTrigger;
                }

                foreach (Collider2D collider in body.GetComponentsInChildren<Collider2D>(true))
                {
                    hasSolidCollider |= !collider.isTrigger;
                }
            }

            return hasSolidCollider;
        }

        /// <summary>
        /// A gateway has to be reachable and must not be where a player arrives: a spawn point inside one sends the
        /// player straight back out the moment they land.
        /// </summary>
        private static void ValidateGateway(GameObject prefab, FieldEntityRecord record, string entityName, List<string> problems)
        {
            if (!HasScript(record, FieldScriptType.Gateway))
            {
                return;
            }

            if (HasScript(record, FieldScriptType.OnEnter))
            {
                problems.Add($"{entityName} has both a {nameof(FieldScriptType.Gateway)} and an {nameof(FieldScriptType.OnEnter)} script. Both run on entering, in the same slot, so only one would — put the other on its own entity");
            }

            FieldCollisionTrigger trigger = record.Body == null ? null : record.Body.GetComponentInChildren<FieldCollisionTrigger>(true);

            if (trigger == null)
            {
                problems.Add($"{entityName} has a {nameof(FieldScriptType.Gateway)} script but no {nameof(FieldCollisionTrigger)}, so nothing runs it");
                return;
            }

            foreach (SpawnPoint spawnPoint in prefab.GetComponentsInChildren<SpawnPoint>(true))
            {
                if (Contains(trigger, spawnPoint.Position))
                {
                    problems.Add($"{prefab.name} / spawn point '{spawnPoint.name}' is inside {entityName}'s gateway, so a player arriving there leaves again at once");
                }
            }
        }

        /// <summary>
        /// Worked out from the box's own space, because a prefab that is not in a scene has no physics bounds. Only a
        /// box is tested; a trigger of another shape is left alone rather than guessed at.
        /// </summary>
        private static bool Contains(FieldCollisionTrigger trigger, Vector3 worldPoint)
        {
            Vector3 local = trigger.transform.InverseTransformPoint(worldPoint);

            if (trigger.TryGetComponent(out BoxCollider box))
            {
                Vector3 offset = local - box.center;
                Vector3 extent = box.size * 0.5f;

                bool insideBox = Mathf.Abs(offset.x) <= extent.x && Mathf.Abs(offset.y) <= extent.y && Mathf.Abs(offset.z) <= extent.z;

                return insideBox;
            }

            if (trigger.TryGetComponent(out BoxCollider2D box2D))
            {
                Vector2 offset2D = (Vector2)local - box2D.offset;
                Vector2 extent2D = box2D.size * 0.5f;

                bool insideBox2D = Mathf.Abs(offset2D.x) <= extent2D.x && Mathf.Abs(offset2D.y) <= extent2D.y;

                return insideBox2D;
            }

            return false;
        }

        public void BuildAssetBundles()
        {
            int count = m_Fields.Count;
            if (count == 0)
            {
                return;
            }

            List<string> problems = ValidateFields();

            if (problems.Count > 0)
            {
                Debug.LogError($"{nameof(FieldDatabase)}::{nameof(BuildAssetBundles)} Not building — {problems.Count} problem(s) in the fields:\n  {string.Join("\n  ", problems)}");
                return;
            }

            if (Directory.Exists(m_AssetBundlesPath))
            {
                Directory.Delete(m_AssetBundlesPath, true);
            }

            Directory.CreateDirectory(m_AssetBundlesPath);

            AssetBundleBuild[] fieldsToBuild = new AssetBundleBuild[count];

            // Each field is bundled from a copy with its scripts compiled, so the prefab being edited keeps only text.
            AssetDatabase.DeleteAsset(FieldExport.BUILD_COPY_FOLDER);
            AssetDatabase.CreateFolder(Path.GetDirectoryName(FieldExport.BUILD_COPY_FOLDER), Path.GetFileName(FieldExport.BUILD_COPY_FOLDER));

            try
            {
                for (int i = 0; i < count; i++)
                {
                    fieldsToBuild[i] = new AssetBundleBuild
                                       {
                                           assetBundleName = m_Fields[i].Prefab.name,
                                           assetNames      = new string[] { FieldExport.WriteBuildCopy(m_Fields[i].Prefab) }
                                       };
                }

                const BuildAssetBundleOptions options = BuildAssetBundleOptions.ChunkBasedCompression | BuildAssetBundleOptions.StrictMode;

                BuildPipeline.BuildAssetBundles(m_AssetBundlesPath, fieldsToBuild, options, EditorUserBuildSettings.activeBuildTarget);
            }
            finally
            {
                AssetDatabase.DeleteAsset(FieldExport.BUILD_COPY_FOLDER);
            }

            AssetDatabase.Refresh();
        }
    }
